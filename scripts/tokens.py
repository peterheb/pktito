#!/usr/bin/env python3
"""ui/tokens.css from design/tokens.json (the pktito design system's tokens):
the fonts, every token as a CSS custom property, light values on :root and
dark ones under prefers-color-scheme, since the app follows the OS theme.
And the same for the Android app's Compose screens, Tokens.kt: each theme's
colors, the fonts (android/fonts.py makes them TTF, which Android takes and
woff2 it does not), the type styles, and the sizes in px as dp."""
import json, os, re

here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
t = json.load(open(os.path.join(here, "design", "tokens.json")))

def value(v, theme):
    if isinstance(v, dict):
        v = v.get(theme, v.get("light"))
    m = re.fullmatch(r"\{([A-Za-z0-9_.-]+)\}", str(v))
    return f"var(--{m.group(1)})" if m else str(v)

light, dark = [], []
for fam in ("color", "shadow"):
    for tok in t.get(fam, {}).get("tokens", []):
        v = tok["value"]
        light.append(f"  --{tok['name']}: {value(v, 'light')};")
        if isinstance(v, dict) and "dark" in v and v["dark"] != v.get("light"):
            dark.append(f"    --{tok['name']}: {value(v, 'dark')};")
for fam in ("spacing", "radius", "layout"):
    for tok in t.get(fam, {}).get("tokens", []):
        light.append(f"  --{tok['name']}: {value(tok['value'], 'light')};")
for name, stack in t["type"]["families"].items():
    light.append(f"  --font-{name}: {stack};")

faces = []
for f in t["type"]["fonts"]:
    faces.append("@font-face { font-family: \"%s\"; src: url(\"%s\") format(\"woff2\"); font-weight: %s; "
                 "font-style: normal; font-display: block; }" % (f["family"], f["file"], f["weight"]))

out = ["/* pktito design system tokens, generated by scripts/tokens.py from design/tokens.json */", ""]
out += faces + ["", ":root {", "  color-scheme: light dark;"] + light + ["}", "",
        "@media (prefers-color-scheme: dark) {", "  :root {"] + dark + ["  }", "}", ""]
open(os.path.join(here, "ui", "tokens.css"), "w").write("\n".join(out))
print("ui/tokens.css:", len(light), "tokens,", len(dark), "with dark values")

# ------------------------------------------------------------- Tokens.kt --

def camel(name):
    head, *rest = re.split(r"[-_]", name)
    return head + "".join(w[:1].upper() + w[1:] for w in rest)

def color(v, theme, toks):
    if isinstance(v, dict):
        v = v.get(theme, v.get("light"))
    m = re.fullmatch(r"\{([A-Za-z0-9_.-]+)\}", str(v))
    if m:
        return color(toks[m.group(1)], theme, toks) + f"  // {{{m.group(1)}}}"
    if v.startswith("#"):
        return f"Color(0xFF{v[1:].upper()})"
    m = re.fullmatch(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)", v)
    r, g, b, a = int(m.group(1)), int(m.group(2)), int(m.group(3)), m.group(4)
    return f"Color(0xFF{r:02X}{g:02X}{b:02X}).copy(alpha = {a}f)"

def font_res(file):
    stem = os.path.splitext(os.path.basename(file))[0]
    return re.sub(r"(?<=[a-z])(?=[A-Z])", "_", stem).replace("-", "_").lower()

toks = {tok["name"]: tok["value"] for tok in t["color"]["tokens"]}
kt = ["// pktito design system tokens, generated by scripts/tokens.py from design/tokens.json",
      "package net.pktito.app.ui", "",
      "import androidx.compose.ui.graphics.Color",
      "import androidx.compose.ui.text.TextStyle",
      "import androidx.compose.ui.text.font.Font",
      "import androidx.compose.ui.text.font.FontFamily",
      "import androidx.compose.ui.text.font.FontWeight",
      "import androidx.compose.ui.text.style.LineHeightStyle",
      "import androidx.compose.ui.unit.dp",
      "import androidx.compose.ui.unit.em",
      "import androidx.compose.ui.unit.sp",
      "import net.pktito.app.R", "",
      "/** A theme's colors, by the tokens' names (design/README.md says where each goes). */",
      "class Palette("]
kt += [f"    val {camel(n)}: Color," for n in toks] + [")", ""]
for theme in ("light", "dark"):
    kt.append(f"val {theme.capitalize()} = Palette(")
    kt += [f"    {camel(n)} = {color(v, theme, toks)}," if "//" not in color(v, theme, toks)
           else f"    {camel(n)} = {color(v, theme, toks).replace('  //', ',  //', 1)}"
           for n, v in toks.items()]
    kt += [")", ""]
fams = {}
for f in t["type"]["fonts"]:
    fams.setdefault(f["family"], []).append(f)
names = {"Archivo": "sans", "Commit Mono": "mono"}
kt.append("object Fonts {")
for fam, fs in fams.items():
    faces = ", ".join(f"Font(R.font.{font_res(f['file'])}, FontWeight.W{f['weight']})" for f in fs)
    kt.append(f"    val {names[fam]} = FontFamily({faces})")
kt += ["}", "",
       "/**",
       " * A line as CSS sets it, as the desktop's text has it: its leading split",
       " * evenly above and below the letters, and kept on the first line and the",
       " * last. Compose's own (LineHeightStyle.Default in ui-text 1.12.1) trims",
       " * both, which set a row's time against its sentence, and a menu's items",
       " * against each other, closer than the desktop's (Peter, 2026-10-25).",
       " */",
       "val CssLine = LineHeightStyle(LineHeightStyle.Alignment.Center, LineHeightStyle.Trim.None)", "",
       "/** The type styles, by their names: transcript is the transcript's, ui the app's working size. */",
       "object Type {"]
for g in t["type"]["groups"]:
    for st in g["styles"]:
        args = [f"fontFamily = Fonts.{g['family']}",
                f"fontWeight = FontWeight.W{st['fontWeight']}",
                f"fontSize = {st['fontSize'].removesuffix('px')}.sp",
                f"lineHeight = {st['lineHeight']}.em",
                "lineHeightStyle = CssLine"]
        if "letterSpacing" in st:
            args.append(f"letterSpacing = ({st['letterSpacing'].removesuffix('em')}).em")
        kt.append(f"    val {camel(st['name'])} = TextStyle({', '.join(args)})")
kt += ["}", ""]
for fam, obj in (("spacing", "Space"), ("radius", "Radius"), ("layout", "Layout")):
    rows = [(tok["name"], tok["value"]) for tok in t[fam]["tokens"]
            if re.fullmatch(r"\d+(px)?", str(tok["value"]))]
    kt.append(f"object {obj} {{")
    kt += [f"    val {camel(n)} = {str(v).removesuffix('px')}.dp" for n, v in rows]
    kt += ["}", ""]
out = os.path.join(here, "android", "app", "src", "main", "kotlin", "net", "pktito", "app", "ui", "Tokens.kt")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(kt))
print("android/.../ui/Tokens.kt:", len(toks), "colors a theme")
